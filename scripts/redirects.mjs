// Builds redirects from old WordPress addresses to the new ones.
// Each content file may carry `legacyUrl: "/old/path/"`; this script also adds
// fixed rules for whole sections. It writes:
//   vercel.json        (used when the site is hosted on Vercel)
//   public/.htaccess   (used when the site is hosted on Hostinger / Apache)
// Run with: npm run redirects   (it also runs before every build)
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const root = process.cwd();
const sections = { publications: '/publications/', news: '/news/', events: '/events/' };

const rules = [];
for (const [dir, base] of Object.entries(sections)) {
  const full = path.join(root, 'content', dir);
  if (!fs.existsSync(full)) continue;
  for (const f of fs.readdirSync(full).filter((x) => x.endsWith('.md'))) {
    const { data, content } = matter(fs.readFileSync(path.join(full, f), 'utf8'));
    if (!data.legacyUrl) continue;
    const slug = f.replace(/\.md$/, '');
    const to = dir === 'events' ? (!data.link && content.trim() ? `${base}${slug}/` : data.link || base) : `${base}${slug}/`;
    if (data.legacyUrl !== to) rules.push([data.legacyUrl, to]);
  }
}

// Section-level rules for old addresses not migrated one by one.
const fixed = [
  ['/reports/', '/publications/?type=report'],
  ['/materials/', '/publications/'],
  ['/reports/toolkit-illicit-financial-flows/:path+', '/publications/toolkit-illicit-financial-flows/'],
  ['/issues/', '/our-work/global-charter/'],
  ['/issues/:path*', '/our-work/global-charter/'],
  ['/conferences/8va-conferencia-internacional-sobre-flujos-financieros-ilicitos-multiples-crisis-y-gobernanza-fiscal-global/', '/events/8th-international-conference-iffs/'],
  ['/conferences/', '/events/'],
  ['/conferences/:path*', '/events/'],
  ['/about-us/', '/about/'],
  ['/category/:path*', '/news/'],
  ['/tag/:path*', '/news/'],
];

const vercel = {
  trailingSlash: true,
  redirects: [...rules, ...fixed].map(([source, destination]) => ({ source, destination, permanent: true })),
};
fs.writeFileSync(path.join(root, 'vercel.json'), JSON.stringify(vercel, null, 2) + '\n');

const esc = (p) => p.replace(/^\//, '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\/$/, '/?');
const ht = [
  '# Generated by scripts/redirects.mjs: do not edit by hand.',
  'ErrorDocument 404 /404.html',
  'RewriteEngine On',
  ...rules.map(([from, to]) => `RewriteRule ^${esc(from)}$ ${to} [R=301,L]`),
  'RewriteRule ^reports/?$ /publications/?type=report [R=301,L]',
  'RewriteRule ^materials/?$ /publications/ [R=301,L]',
  'RewriteRule ^reports/toolkit-illicit-financial-flows/.+ /publications/toolkit-illicit-financial-flows/ [R=301,L]',
  'RewriteRule ^issues(/.*)?$ /our-work/global-charter/ [R=301,L]',
  'RewriteRule ^conferences/8va-conferencia-internacional-sobre-flujos-financieros-ilicitos-multiples-crisis-y-gobernanza-fiscal-global/?$ /events/8th-international-conference-iffs/ [R=301,L]',
  'RewriteRule ^conferences(/.*)?$ /events/ [R=301,L]',
  'RewriteRule ^about-us/?$ /about/ [R=301,L]',
  'RewriteRule ^(category|tag)/ /news/ [R=301,L]',
];
fs.writeFileSync(path.join(root, 'public', '.htaccess'), ht.join('\n') + '\n');
console.log(`redirects: ${rules.length} one-to-one, ${fixed.length} section rules`);
